/** @return list<string> YYYY-MM-DD */
function kinesica_argentina_holidays(): array
{
    static $list = null;
    if (is_array($list)) {
        return $list;
    }
    $list = [];
    foreach (KINESICA_BACKUP_HOLIDAYS as $d) {
        $d = (string) $d;
        if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $d)) {
            $list[] = $d;
        }
    }
    return $list;
}
